function [qeq, lambdaeq, exitflag] = FindEquilibrium( ...
                    Linkage, Carriage, ...
                    s,q_guess, ...
                    T_0_fixed, T_L_fixed)

    n_beam = Linkage.ndof;
    n_mass = Carriage.ndof;
    n      = n_beam + n_mass;

    % determine number of constraints once
    qd = zeros(n,1);
    % 
    % [s,~] = ProjectS(Linkage, ...
    %                  q_guess(1:n_beam), ...
    %                  q_guess(n_beam+1:end), ...
    %                  Linkage.VLinks(1).L/2);

    [err0, J0, Jd0,errL,JL,JdL] = ErrorDynamicsAt0andL( ...
                     Linkage,Carriage,...
                     q_guess(1:n_beam),...
                     zeros(n_beam,1),...
                     T_0_fixed,T_L_fixed);

    [err_mass, J_mass_full] = ErrorJAtS_fixed( ...
                     Linkage,Carriage,...
                     s,q_guess,qd);

    nc = length(err_mass) + length(err0) + length(errL);

    x0 = [q_guess;
          zeros(nc,1)];

    opts = optimoptions('fsolve',...
                        'Display','iter',...
                        'Algorithm','trust-region-dogleg');

    [xsol,~,exitflag] = fsolve(@residual,x0,opts);

    qeq      = xsol(1:n);
    lambdaeq = xsol(n+1:end);


    %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
    function r = residual(x)

        q      = x(1:n);
        lambda = x(n+1:end);
        qd = zeros(n,1);

        q_b    = q(1:n_beam);
        q_mass = q(n_beam+1:end);

        %--------------------------------
        % Internal coordinate
        %--------------------------------
        % [s,~] = ProjectS(Linkage,...
        %                  q_b,...
        %                  q_mass,...
        %                  Linkage.VLinks(1).L/2);
        % s = 
        %--------------------------------
        % Beam dynamics
        %--------------------------------
        [ID_no_Mqdd, tau] = ...
            DAEJacobians(Linkage,...
                         0.0,...
                         q_b,...
                         zeros(n_beam,1),...
                         zeros(n_beam,1),...
                         [],[],[]);

        %--------------------------------
        % Carriage dynamics
        %--------------------------------
        [ID_no_Mqddm,~,~,~,~,~] = ...
            DAEJacobians(Carriage,...
                         0.0,...
                         q_mass,...
                         zeros(n_mass,1),...
                         zeros(n_mass,1),...
                         [],[],[]);

        %--------------------------------
        % Constraints
        %--------------------------------
        [err0, J0, ~,...
         errL, JL, ~] ...
            = ErrorDynamicsAt0andL( ...
                Linkage,Carriage,...
                q_b,...
                zeros(n_beam,1),...
                T_0_fixed,...
                T_L_fixed);

        [err_mass,...
         J_mass_full,...
         ~] ...
            = ErrorJAtS_fixed( ...
                Linkage,...
                Carriage,...
                s,...
                q,...
                qd);
        
        Jc = [J_mass_full;
              J0;
              JL];
        
        phi = [err_mass;
               err0;
               errL];
      

        %--------------------------------
        % Generalized forces
        %--------------------------------
        g_full = zeros(n,1);

        g_full(1:n_beam)    = -ID_no_Mqdd + tau;
        g_full(n_beam+1:n)  = -ID_no_Mqddm;

        %--------------------------------
        % Static equilibrium equations
        %--------------------------------
        force_balance = g_full  + Jc'*lambda;

        r = [force_balance;
             phi];

    end

end