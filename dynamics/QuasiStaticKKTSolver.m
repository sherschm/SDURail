function [tvec_out,x_out] = QuasiStaticKKTSolver( ...
    Linkage,...
    Carriage,...
    q0,...
    tf,...
    dt,...
    T_0_fixed,...
    T_L_fixed,...
    controller,...
    carriage_constraints)

n_beam = Linkage.ndof;
n_mass = Carriage.ndof;
n      = n_beam + n_mass;

tvec_out = (0:dt:tf)';
Nsteps   = numel(tvec_out);

x_out = zeros(Nsteps,n);

q = q0(:);

for k = 1:Nsteps

    t = tvec_out(k);

    q = SolveEquilibrium( ...
        q,...
        t,...
        Linkage,...
        Carriage,...
        T_0_fixed,...
        T_L_fixed,...
        controller,...
        carriage_constraints);

    x_out(k,:) = q.';
end

end

function q = SolveEquilibrium( ...
    q,...
    t,...
    Linkage,...
    Carriage,...
    T_0_fixed,...
    T_L_fixed,...
    controller,...
    carriage_constraints)

maxIter = 30;
tol     = 1e-8;

n = length(q);

lambda = zeros(NumberOfConstraints(...),1);

for iter = 1:maxIter

    [R,J] = ResidualAndJacobian( ...
        q,...
        lambda,...
        t,...
        Linkage,...
        Carriage,...
        T_0_fixed,...
        T_L_fixed,...
        controller,...
        carriage_constraints);

    if norm(R) < tol
        return;
    end

    dz = -J\R;

    dq      = dz(1:n);
    dlambda = dz(n+1:end);

    q      = q + dq;
    lambda = lambda + dlambda;

end

error('Quasi-static solve failed');

end